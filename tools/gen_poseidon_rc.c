/*
 * gen_poseidon_rc.c — writes src/zkn_mont/zkn_poseidon_rc_bn254.h, the
 * Poseidon (circomlib, BN254) round constants for t = 2..8, as flash tables.
 *
 * The constants are produced with the Grain LFSR exactly as
 * zkn_poseidon_soft.c generated them at run time before the tables existed
 * (same seed encoding, warm-up, bit pairing, 62/64/64/64-bit split and
 * top-64-bit rejection), so the hashes do not change. Generating them on the
 * device cost about 1.8 ms per constant on a Nano S Plus, i.e. 0.25 s for
 * Poseidon-1 up to 1.07 s for Poseidon-7, nearly all of each hash.
 *
 * Build and run on a host:
 *   cc -O2 -DZKN_HOST_BUILD -o /tmp/gen_poseidon_rc tools/gen_poseidon_rc.c
 *   /tmp/gen_poseidon_rc > src/zkn_mont/zkn_poseidon_rc_bn254.h
 *
 * Host-only: the Ledger SDK app build sweeps every .c under the submodule,
 * so without ZKN_HOST_BUILD this file is an empty translation unit.
 */
#ifdef ZKN_HOST_BUILD

#include <stdint.h>
#include <stdio.h>
#include <stddef.h>

#define GRAIN_TAPS \
    ((1ULL << 0) | (1ULL << 13) | (1ULL << 23) | \
     (1ULL << 38) | (1ULL << 51) | (1ULL << 62))

#define BJJ_FIELD_SIZE             254
#define BJJ_GRAIN_TOP64_THRESHOLD  0x30644e72e131a029ULL
#define NROUNDS_F                  8

static const size_t NROUNDS_P[] = {56, 57, 56, 60, 60, 63, 64}; /* t = 2..8 */

static uint64_t grain_lfsr_advance(uint64_t state[2])
{
    uint64_t feedback = state[0] & GRAIN_TAPS;

    feedback = (feedback >> 32) ^ feedback;
    feedback = (feedback >> 16) ^ feedback;
    feedback = (feedback >>  8) ^ feedback;
    feedback = (feedback >>  4) ^ feedback;
    feedback = (feedback >>  2) ^ feedback;
    feedback = ((feedback >> 1) ^ feedback) & 1;

    state[0] = (state[0] >> 1) ^ ((state[1] & 1) << 63);
    state[1] = (state[1] >> 1) ^ (feedback << 15);

    return feedback & 1;
}

static uint64_t next64_graingen(uint64_t state[2], size_t len)
{
    uint64_t out = 0;
    size_t cpt = 0;
    uint64_t temp;

    while (cpt < len) {
        temp = grain_lfsr_advance(state);
        temp = (temp << 1) + grain_lfsr_advance(state);
        if (temp & 0x2) {
            out = (out << 1) + (temp & 1);
            cpt++;
        }
    }
    return out;
}

static void init_generator(uint64_t state[2], size_t field_size, size_t t,
                           size_t nRoundsF, size_t nRoundsP)
{
    uint8_t bits[80];
    int pos = 0;

    bits[pos++] = 0; bits[pos++] = 1;                                   /* field GF(p) */
    for (int i = 3; i >= 0; i--) bits[pos++] = 0;                       /* sbox x^alpha */
    for (int i = 11; i >= 0; i--) bits[pos++] = (field_size >> i) & 1;
    for (int i = 11; i >= 0; i--) bits[pos++] = (t >> i) & 1;
    for (int i = 9; i >= 0; i--) bits[pos++] = (nRoundsF >> i) & 1;
    for (int i = 9; i >= 0; i--) bits[pos++] = (nRoundsP >> i) & 1;
    for (int i = 0; i < 30; i++) bits[pos++] = 1;

    state[0] = 0;
    state[1] = 0;
    for (int i = 0; i < 64; i++) state[0] |= ((uint64_t)bits[i]) << i;
    for (int i = 64; i < 80; i++) state[1] |= ((uint64_t)bits[i]) << (i - 64);

    for (int i = 0; i < 160; i++) grain_lfsr_advance(state);
}

/* One constant as 32 big-endian bytes: the buffer zkn_bn_init read. */
static void gen_constant(uint64_t state[2], uint8_t out[32])
{
    uint64_t w[4];

    do {
        w[0] = next64_graingen(state, BJJ_FIELD_SIZE - 192);
        w[1] = next64_graingen(state, 64);
        w[2] = next64_graingen(state, 64);
        w[3] = next64_graingen(state, 64);
    } while (w[0] > BJJ_GRAIN_TOP64_THRESHOLD);

    for (int i = 0; i < 4; i++)
        for (int b = 0; b < 8; b++)
            out[8 * i + b] = (uint8_t)(w[i] >> (56 - 8 * b));
}

int main(void)
{
    size_t offsets[7];
    size_t total = 0;

    for (size_t k = 0; k < 7; k++) {
        size_t t = k + 2;
        offsets[k] = total;
        total += t * (NROUNDS_F + NROUNDS_P[k]);
    }

    printf("/*\n"
           " * zkn_poseidon_rc_bn254.h — GENERATED by tools/gen_poseidon_rc.c, do not edit.\n"
           " *\n"
           " * Poseidon (circomlib, BN254 scalar field) round constants for t = 2..8\n"
           " * (Poseidon-1 .. Poseidon-7), in the order the rounds consume them: for\n"
           " * each of the RF + RP rounds, t constants. Each is 32 big-endian bytes.\n"
           " * Grain LFSR output, identical to what zkn_poseidon_soft.c generated at\n"
           " * run time before these tables.\n"
           " */\n"
           "#ifndef ZKN_POSEIDON_RC_BN254_H\n"
           "#define ZKN_POSEIDON_RC_BN254_H\n\n"
           "#include <stdint.h>\n\n"
           "#define ZKN_POSEIDON_RC_COUNT %zuu\n\n", total);

    printf("/* Index of the first constant for t = 2..8. */\n"
           "static const uint16_t ZKN_POSEIDON_RC_OFFSET[7] = {");
    for (size_t k = 0; k < 7; k++) printf("%s%zu", k ? ", " : "", offsets[k]);
    printf("};\n\n");

    printf("static const uint8_t ZKN_POSEIDON_RC_BN254[ZKN_POSEIDON_RC_COUNT * 32] = {\n");
    for (size_t k = 0; k < 7; k++) {
        size_t t = k + 2;
        size_t n = t * (NROUNDS_F + NROUNDS_P[k]);
        uint64_t state[2];
        uint8_t c[32];

        init_generator(state, BJJ_FIELD_SIZE, t, NROUNDS_F, NROUNDS_P[k]);
        printf("    /* t = %zu: %zu constants */\n", t, n);
        for (size_t i = 0; i < n; i++) {
            gen_constant(state, c);
            printf("   ");
            for (int b = 0; b < 32; b++) printf(" 0x%02x,", c[b]);
            printf("\n");
        }
    }
    printf("};\n\n#endif /* ZKN_POSEIDON_RC_BN254_H */\n");
    return 0;
}

#endif /* ZKN_HOST_BUILD */
