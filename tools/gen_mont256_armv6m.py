#!/usr/bin/env python3
"""Generate src/zkn_mont/zkn_mont256_armv6m_fields.inc.

    python3 tools/gen_mont256_armv6m.py            # write the file
    python3 tools/gen_mont256_armv6m.py --check    # fail if the file on disk differs
    python3 tools/gen_mont256_armv6m.py --stats    # cost of each reduction row

zkn_mont256_armv6m.S has a path of its own for the two fields the curves are
defined over. In that path the reduction of the Montgomery product multiplies
by constants, the limbs of p, so it needs no MULS: each m * p[j] is a fixed
sequence of shifts, additions and subtractions read off the non-adjacent form
of p[j]. On a core whose multiplier takes 32 cycles this is three to four
times cheaper than the four MULS of the generic row.

For each field this file emits three assembler macros:

    CHECK_P_<F>  other    compare p[1..7] with the field, branch to other if
                          it is another modulus (p[0] follows from n0)
    MONT_M_<F>            r1 = t[0] * n0 mod 2^32
    REDROW_<F>            t = (t + m * p) >> 32, carry out in r3

Registers of REDROW: r1 = m, r2 = 0, r5 = low word, r3 and r4 = high word and
incoming carry, swapping at each limb, r6 and r7 = scratch. t is at sp.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "zkn_mont", "zkn_mont256_armv6m_fields.inc")

M32 = 0xFFFFFFFF
FIELDS = [
    ("BN254R", "BN254 r, the base field of BabyJubjub",
     0x30644E72E131A029B85045B68181585D2833E84879B9709143E1F593F0000001),
    ("BLS12381R", "BLS12-381 r, the base field of Bandersnatch",
     0x73EDA753299D7D483339D80809A1D80553BDA402FFFE5BFEFFFFFFFF00000001),
]


def naf(x):
    """Non-adjacent form of x >= 0: [(bit, +1 or -1)], highest bit first."""
    out, k = [], 0
    while x:
        if x & 1:
            d = 2 - (x & 3)
            x -= d
            out.append((k, d))
        x >>= 1
        k += 1
    return out[::-1]


def describe(terms):
    return " ".join(("+" if s > 0 else "-") + ("1" if k == 0 else f"2^{k}") for k, s in terms)


def limb_code(j, limb):
    """(lines, cycles) of (hi : t[j-1]) = m * p[j] + t[j] + carry in."""
    hi, cin = ("r4", "r3") if j % 2 == 0 else ("r3", "r4")
    terms = naf(limb)
    assert terms and terms[0][1] > 0
    lines = [f"    @ p[{j}] = 0x{limb:08x} = {describe(terms)}"]
    cycles = 0
    k, _ = terms[0]
    if k == 32:
        lines += ["    movs    r5, #0", f"    mov     {hi}, r1"]
    elif k == 0:
        lines += ["    mov     r5, r1", f"    movs    {hi}, #0"]
    else:
        lines += [f"    lsls    r5, r1, #{k}", f"    lsrs    {hi}, r1, #{32 - k}"]
    cycles += 2
    for k, s in terms[1:]:
        lo_op, hi_op = ("adds", "adcs") if s > 0 else ("subs", "sbcs")
        if k == 32:
            lines += [f"    {lo_op}    {hi}, {hi}, r1"]
            cycles += 1
        elif k == 0:
            lines += [f"    {lo_op}    r5, r5, r1", f"    {hi_op}    {hi}, r2"]
            cycles += 2
        else:
            lines += [f"    lsls    r6, r1, #{k}", f"    lsrs    r7, r1, #{32 - k}",
                      f"    {lo_op}    r5, r5, r6", f"    {hi_op}    {hi}, r7"]
            cycles += 4
    lines += [f"    ldr     r6, [sp, #{4 * j}]", "    adds    r5, r5, r6", f"    adcs    {hi}, r2"]
    cycles += 4
    if j:
        lines += [f"    adds    r5, r5, {cin}", f"    adcs    {hi}, r2", f"    str     r5, [sp, #{4 * (j - 1)}]"]
        cycles += 4
    return lines, cycles


def m_code(n0):
    """(lines, cycles) of r1 = t[0] * n0 mod 2^32."""
    terms = [(k, s) for k, s in naf(n0) if k < 32]
    lines = [f"    @ n0 = 0x{n0:08x} = {describe(terms)} mod 2^32", "    ldr     r1, [sp, #0]"]
    cycles = 2
    k, first = terms[0]
    lines.append("    mov     r0, r1" if k == 0 else f"    lsls    r0, r1, #{k}")
    cycles += 1
    for k, s in terms[1:]:
        op = "adds" if s == first else "subs"
        if k == 0:
            lines.append(f"    {op}    r0, r0, r1")
            cycles += 1
        else:
            lines += [f"    lsls    r6, r1, #{k}", f"    {op}    r0, r0, r6"]
            cycles += 2
    lines.append("    rsbs    r1, r0, #0" if first < 0 else "    mov     r1, r0")
    return lines, cycles + 1


def generate():
    out = ["/* zkn_mont256_armv6m_fields.inc",
           " * SPDX-License-Identifier: Apache-2.0",
           " * Copyright (c) 2025 ZKNOX",
           " *",
           " * Generated by tools/gen_mont256_armv6m.py. Do not edit: change the",
           " * generator and run it again. Included by zkn_mont256_armv6m.S.",
           " *",
           " * Reduction rows of the Montgomery product for the fields the curves are",
           " * defined over, with the multiplications by the limbs of p written as",
           " * shifts, additions and subtractions. The sequences depend on p alone.",
           " */", ""]
    stats = []
    for tag, what, p in FIELDS:
        limbs = [(p >> (32 * i)) & M32 for i in range(8)]
        n0 = (-pow(p, -1, 1 << 32)) & M32
        out += [f"/* ── {what} ── */", f"#define N0_{tag} 0x{n0:08x}", ""]
        out += [f".macro CHECK_P_{tag} other"]
        for j in range(1, 8):
            out += [f"    ldr     r5, [r3, #{4 * j}]", f"    ldr     r6, =0x{limbs[j]:08x}",
                    "    cmp     r5, r6", "    bne     \\other"]
        out += [".endm", ""]
        lines, m_cycles = m_code(n0)
        out += [f".macro MONT_M_{tag}"] + lines + [".endm", ""]
        out += [f".macro REDROW_{tag}", "    movs    r2, #0"]
        row_cycles, per_limb = 1, []
        for j, limb in enumerate(limbs):
            lines, c = limb_code(j, limb)
            out += lines
            row_cycles += c
            per_limb.append(c)
        out += [".endm", ""]
        stats.append((what, n0, m_cycles, row_cycles, per_limb))
    return "\n".join(out), stats


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="compare with the file on disk, write nothing")
    ap.add_argument("--stats", action="store_true", help="print the cycles of each row")
    args = ap.parse_args()
    text, stats = generate()
    if args.stats:
        for what, n0, m_cycles, row_cycles, per_limb in stats:
            print(f"{what}: m in {m_cycles} cycles, row in {row_cycles} ({per_limb}), no MULS")
        return 0
    if args.check:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("zkn_mont256_armv6m_fields.inc is up to date" if same else "zkn_mont256_armv6m_fields.inc differs from the generator")
        return 0 if same else 1
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
