/** Load a G2 point from 4 × 48-byte BE arrays (normal form). */
static void load_g2(zkn_g2_384_t *Q,
                    const uint8_t x0[48], const uint8_t x1[48],
                    const uint8_t y0[48], const uint8_t y1[48],
                    const zkn_mont_ctx384_t *ctx)
{
    zkn_fp2_384_t x, y;
    zkn_fe384_from_be(x.c0, x0);
    zkn_fe384_from_be(x.c1, x1);
    zkn_fe384_from_be(y.c0, y0);
    zkn_fe384_from_be(y.c1, y1);
    zkn_g2_384_from_affine(Q, &x, &y, ctx);   /* does to_mont internally */
}

/** Load a G1 point from 2 × 48-byte BE arrays (normal form). */
static void load_g1(zkn_g1_384_t *P,
                    const uint8_t px[48], const uint8_t py[48],
                    const zkn_mont_ctx384_t *ctx)
{
    zkn_fe384_t x, y;
    zkn_fe384_from_be(x, px);
    zkn_fe384_from_be(y, py);
    zkn_g1_384_from_affine(P, x, y, ctx);      /* does to_mont internally */
}

/** Load precomputed e(α,β) into an Fp12 in Montgomery form. */
static void load_alpha_beta(zkn_fp12_384_t *ab,
                            const zkn_mont_ctx384_t *ctx)
{
    const zkn_fp2_384_t *fp2[6] = {
        &ab->c0.c0, &ab->c0.c1, &ab->c0.c2,
        &ab->c1.c0, &ab->c1.c1, &ab->c1.c2
    };

    /* VK_ALPHA_BETA[2*i]   = c0 of Fp2 slot i
     * VK_ALPHA_BETA[2*i+1] = c1 of Fp2 slot i */
    zkn_fe384_t t;
    for (int i = 0; i < 6; i++) {
        zkn_fp2_384_t *dst = (zkn_fp2_384_t *)fp2[i];

        zkn_fe384_from_be(t, VK_ALPHA_BETA[2 * i]);
        zkn_to_mont_384(dst->c0, t, ctx);

        zkn_fe384_from_be(t, VK_ALPHA_BETA[2 * i + 1]);
        zkn_to_mont_384(dst->c1, t, ctx);
    }
}

/* ══════════════════════════════════════════════════════════════════════
 *  Public API
 * ══════════════════════════════════════════════════════════════════════ */

int zkn_groth16_verify(const uint8_t proof_buf[ZKN_GROTH16_PROOF_LEN],
                       const zkn_mont_ctx384_t *ctx)
{
    const uint8_t *ptr = proof_buf;

    /* ── 1. Deserialise proof inputs ─────────────────────────────── */

    /* π.A ∈ G1 (96 B) */
    zkn_g1_384_t pi_a;
    zkn_fe384_t ax, ay;
    zkn_fe384_from_be(ax, ptr);
    zkn_fe384_from_be(ay, ptr + 48);
    zkn_g1_384_from_affine(&pi_a, ax, ay, ctx);
    ptr += 96;

    /* π.B ∈ G2 (192 B) */
    zkn_g2_384_t pi_b;
    {
        zkn_fp2_384_t bx, by;
        zkn_fe384_from_be(bx.c0, ptr);
        zkn_fe384_from_be(bx.c1, ptr + 48);
        zkn_fe384_from_be(by.c0, ptr + 96);
        zkn_fe384_from_be(by.c1, ptr + 144);
        zkn_g2_384_from_affine(&pi_b, &bx, &by, ctx);
    }
    ptr += 192;

    /* π.C ∈ G1 (96 B) */
    zkn_g1_384_t pi_c;
    zkn_fe384_t cx, cy;
    zkn_fe384_from_be(cx, ptr);
    zkn_fe384_from_be(cy, ptr + 48);
    zkn_g1_384_from_affine(&pi_c, cx, cy, ctx);
    ptr += 96;

    /* pub[0] = H_tx (32 B), pub[1] = H_str (32 B) */
    const uint8_t *h_tx  = ptr;
    const uint8_t *h_str = ptr + ZKN_GROTH16_SCALAR_LEN;

    /* ── 2. Load hardcoded VK ────────────────────────────────────── */

    zkn_g1_384_t ic0, ic1, ic2;
    load_g1(&ic0, VK_IC0_X, VK_IC0_Y, ctx);
    load_g1(&ic1, VK_IC1_X, VK_IC1_Y, ctx);
    load_g1(&ic2, VK_IC2_X, VK_IC2_Y, ctx);

    zkn_g2_384_t gamma, delta;
    load_g2(&gamma, VK_GAMMA_X0, VK_GAMMA_X1, VK_GAMMA_Y0, VK_GAMMA_Y1, ctx);
    load_g2(&delta, VK_DELTA_X0, VK_DELTA_X1, VK_DELTA_Y0, VK_DELTA_Y1, ctx);

    /* ── 3. Compute vk_x = IC[0] + H_tx·IC[1] + H_str·IC[2] ──── */

    zkn_g1_384_t tmp, vk_x;

    /* H_tx · IC[1] */
    zkn_g1_384_mul(&tmp, &ic1, h_tx, ZKN_GROTH16_SCALAR_LEN, ctx);
    /* IC[0] + H_tx · IC[1] */
    zkn_g1_384_add(&vk_x, &ic0, &tmp, ctx);
    /* H_str · IC[2] */
    zkn_g1_384_mul(&tmp, &ic2, h_str, ZKN_GROTH16_SCALAR_LEN, ctx);
    /* vk_x = IC[0] + H_tx·IC[1] + H_str·IC[2] */
    zkn_g1_384_add(&vk_x, &vk_x, &tmp, ctx);

    /* ── 4. Negate G1 points for the equation LHS ────────────────
     *
     *   LHS = e(π.A, π.B) · e(-vk_x, γ) · e(-π.C, δ)
     *   Compare LHS == e(α, β)
     * ──────────────────────────────────────────────────────────── */

    zkn_g1_384_t neg_vk_x, neg_pi_c;
    zkn_g1_384_neg(&neg_vk_x, &vk_x, ctx);
    zkn_g1_384_neg(&neg_pi_c, &pi_c, ctx);

    /* ── 5. Batch Miller loop (3 pairs) + single final exp ─────── */

    const zkn_g1_384_t *Ps[3] = { &pi_a,    &neg_vk_x, &neg_pi_c };
    const zkn_g2_384_t *Qs[3] = { &pi_b,    &gamma,    &delta    };

    zkn_fp12_384_t f;
    zkn_miller_loop_n(&f, Ps, Qs, 3, ctx);
    zkn_final_exp(&f, &f, ctx);

    /* ── 6. Compare with precomputed e(α, β) ─────────────────── */

    zkn_fp12_384_t alpha_beta;
    load_alpha_beta(&alpha_beta, ctx);

    return zkn_fp12_384_eq(&f, &alpha_beta) ? 1 : 0;
}

/* ══════════════════════════════════════════════════════════════════════
 *  Generic Groth16 verifier (parameterized VK)
 *
 *  4-pairing batch: e(A, B) · e(−vk_x, γ) · e(−C, δ) · e(−α, β) == 1
 * ══════════════════════════════════════════════════════════════════════ */

static void load_g1_generic(zkn_g1_384_t *P, const uint8_t buf[96],
                            const zkn_mont_ctx384_t *ctx)
{
    int z = 1;
    for (int i = 0; i < 96 && z; i++) if (buf[i]) z = 0;
    if (z) { zkn_g1_384_zero(P); return; }
    zkn_fe384_t x, y;
    zkn_fe384_from_be(x, buf);
    zkn_fe384_from_be(y, buf + 48);
    zkn_g1_384_from_affine(P, x, y, ctx);
}

static void load_g2_generic(zkn_g2_384_t *Q, const uint8_t buf[192],
                            const zkn_mont_ctx384_t *ctx)
{
    zkn_fp2_384_t x, y;
    zkn_fe384_from_be(x.c0, buf);
    zkn_fe384_from_be(x.c1, buf + 48);
    zkn_fe384_from_be(y.c0, buf + 96);
    zkn_fe384_from_be(y.c1, buf + 144);
    zkn_g2_384_from_affine(Q, &x, &y, ctx);
}

int zkn_groth16_verify_generic(
    const zkn_groth16_vk_generic_t    *vk,
    const zkn_groth16_proof_generic_t *proof,
    const uint8_t                     (*pub)[32],
    int                                n_pub,
    const zkn_mont_ctx384_t           *ctx)
{
    if (n_pub != vk->n_public || n_pub < 0 || n_pub > ZKN_GROTH16_MAX_PUB)
        return 0;

    /* Load proof points */
    zkn_g1_384_t pA, pC;
    zkn_g2_384_t pB;
    load_g1_generic(&pA, proof->A, ctx);
    load_g2_generic(&pB, proof->B, ctx);
    load_g1_generic(&pC, proof->C, ctx);

    /* Load VK points */
    zkn_g1_384_t vAlpha;
    zkn_g2_384_t vBeta, vGamma, vDelta;
    load_g1_generic(&vAlpha, vk->alpha, ctx);
    load_g2_generic(&vBeta,  vk->beta,  ctx);
    load_g2_generic(&vGamma, vk->gamma, ctx);
    load_g2_generic(&vDelta, vk->delta, ctx);

    /* Compute vk_x = IC[0] + Σ pub[i]·IC[i+1] */
    zkn_g1_384_t vk_x;
    load_g1_generic(&vk_x, vk->IC[0], ctx);

    for (int i = 0; i < n_pub; i++) {
        zkn_g1_384_t ic_i;
        load_g1_generic(&ic_i, vk->IC[i + 1], ctx);
        /* pub[i] is 32-byte BE scalar */
        zkn_g1_384_t tmp;
        zkn_g1_384_mul(&tmp, &ic_i, pub[i], 32, ctx);
        zkn_g1_384_add(&vk_x, &vk_x, &tmp, ctx);
    }

    /* Negate for batch check */
    zkn_g1_384_t neg_vk_x, neg_C, neg_alpha;
    zkn_g1_384_neg(&neg_vk_x,  &vk_x,   ctx);
    zkn_g1_384_neg(&neg_C,     &pC,      ctx);
    zkn_g1_384_neg(&neg_alpha, &vAlpha,  ctx);

    /* 4-pairing batch: e(A,B) · e(-vk_x,γ) · e(-C,δ) · e(-α,β) == 1 */
    const zkn_g1_384_t *Ps[4] = { &pA,      &neg_vk_x, &neg_C,  &neg_alpha };
    const zkn_g2_384_t *Qs[4] = { &pB,      &vGamma,   &vDelta, &vBeta     };

    zkn_fp12_384_t f;
    zkn_miller_loop_n(&f, Ps, Qs, 4, ctx);
    zkn_final_exp(&f, &f, ctx);

    zkn_fp12_384_t one;
    zkn_fp12_384_one(&one, ctx);

    return zkn_fp12_384_eq(&f, &one) ? 1 : 0;
}
