/*
 * zkn_groth16.c — BLS12-381 Groth16 proof verification
 *
 * Hardcoded verification key for the ZKNOX circuit (nPublic = 2).
 *
 * Verification equation:
 *   e(π.A, π.B) · e(−vk_x, γ) · e(−π.C, δ) == e(α, β)
 *
 * where vk_x = IC[0] + pub[0]·IC[1] + pub[1]·IC[2]
 *
 * We batch the 3 LHS pairings into a single miller_loop_n + final_exp,
 * then compare against the precomputed e(α,β).
 *
 * Copyright (c) 2025 ZKNOX / Kohaku
 */

