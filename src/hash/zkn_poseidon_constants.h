// tEdwards curve defined by {a}*x^2 + y^2 = 1 + {d} * x^2*y^2"
typedef struct
{
  size_t fieldsize8;
  size_t nb_inputs;      // the number of elements equal to the number of elements of the permutation
  size_t nb_state_cells; // the number of elements of the state

  uint8_t pow[1]; // the pow used in sigma, 3 (if p!=1 mod ) or 5

  uint32_t status;

  zkn_bn_mont_ctx_t *mont; // pointer to an already initialized montgomery context
  zkn_bn_t state[_MAX_POSEIDON_nCELLS];
  zkn_bn_t MixColumn[_MAX_POSEIDON_nCELLS * _MAX_POSEIDON_nCELLS];

#ifdef _DYN_GEN
  uint64_t grain_state[2];
#endif

  size_t current_index;

  // for local computations
  zkn_bn_t temp;                     // to store a single value
  zkn_bn_t tmp[_MAX_POSEIDON_INPUT]; // to copy the state

} poseidon_ctx_t;

