// tEdwards curve defined by {a}*x^2 + y^2 = 1 + {d} * x^2*y^2"
typedef struct
{
  size_t fieldsize8;
  size_t nb_inputs;      // the number of elements equal to the number of elements of the permutation
  size_t nb_state_cells; // the number of elements of the state

  uint8_t pow[1]; // the pow used in sigma, 3 (if p!=1 mod ) or 5
  size_t  rounds_f;
  size_t  rounds_p;

  uint32_t status;

  zkn_bn_mont_ctx_t *mont; // pointer to an already initialized montgomery context
  /*
   * Borrowed public handle for the modulus. cx_bn_mont_ctx_t internals are
   * private on Ledger and must never be passed to the public cx_bn API.
   */
  zkn_bn_t modulus;
  zkn_bn_t state[_MAX_POSEIDON_nCELLS];
  zkn_bn_t MixColumn[_MAX_POSEIDON_nCELLS * _MAX_POSEIDON_nCELLS];

  /* A full t*t MDS allocation fits in the CX pool through t=6
   * (Poseidon-5). For Poseidon-6/7, keep the matrix in flash and stream
   * one coefficient through mix_constant instead. */
  const uint8_t *mix_src;
  zkn_bn_t mix_constant;
  uint8_t stream_mix;

#ifdef _DYN_GEN
  uint64_t grain_state[2];
#endif

  size_t current_index;

  // for local computations
  zkn_bn_t temp;                     // to store a single value
  zkn_bn_t tmp[_MAX_POSEIDON_nCELLS]; // to copy the state (must be nb_state_cells = nb_inputs+1, NOT nb_inputs)

} poseidon_ctx_t;

