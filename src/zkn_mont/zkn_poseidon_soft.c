/* Partial round counts from the Poseidon paper (table 2), indexed by t-2 */
static const size_t POSEIDON_NROUNDS_P_TABLE[] = {
    56, 57, 56, 60, 60, 63, 64, 63, 60, 66, 60, 65, 70, 60, 64, 68
};

int zkn_poseidon_init(poseidon_soft_ctx_t *ctx,
                      uint32_t pow,
                      size_t nb_inputs,
                      zkn_bn_mont_ctx_t *montctx)
{
    if (nb_inputs == 0 || nb_inputs > POSEIDON_MAX_INPUTS)
        return ZKN_INVALID_PARAM;

    size_t t = nb_inputs + 1;

    ctx->pow = (uint8_t)pow;
    ctx->nb_inputs = nb_inputs;
    ctx->nb_state_cells = t;
    ctx->rounds_f = POSEIDON_NROUNDS_F;
    ctx->rounds_p = POSEIDON_NROUNDS_P_TABLE[t - 2];
    ctx->mont = montctx;

    init_generator(ctx->grain_state, BJJ_FIELD_SIZE, t,
                   ctx->rounds_f, ctx->rounds_p);

    /* Select the MDS matrix for this arity */
    const uint8_t *mix_src;
    switch (nb_inputs) {
    case 1:  mix_src = POSEIDON1_MIXCOLUMN; break;
    case 2:  mix_src = POSEIDON2_MIXCOLUMN; break;
    case 3:  mix_src = POSEIDON3_MIXCOLUMN; break;
    case 4:  mix_src = POSEIDON4_MIXCOLUMN; break;
    case 5:  mix_src = POSEIDON5_MIXCOLUMN; break;
    case 6:  mix_src = POSEIDON6_MIXCOLUMN; break;
    case 7:  mix_src = POSEIDON7_MIXCOLUMN; break;
    default: return ZKN_INVALID_PARAM;
    }

    /* Init scratch */
    zkn_bn_alloc(&ctx->temp, 32);
    for (size_t i = 0; i < t; i++) {
        zkn_bn_alloc(&ctx->state[i], 32);
        zkn_bn_alloc(&ctx->tmp[i], 32);
    }

    /* Load and montgomize MixColumn matrix */
    for (size_t i = 0; i < t; i++) {
        for (size_t j = 0; j < t; j++) {
            size_t idx = i * t + j;
            ZKN_CHECK(zkn_bn_init(ctx->MixColumn[idx],
                                  mix_src + 32 * idx, 32));
            ZKN_CHECK(zkn_mont_to_montgomery(ctx->MixColumn[idx],
                                             ctx->MixColumn[idx],
                                             ctx->mont));
        }
    }

    ctx->status = POSEIDON_INITIALIZED;
    return ZKN_OK;
}

int zkn_poseidon(poseidon_soft_ctx_t *ctx,
                 uint32_t initState,
                 zkn_bn_t *out,
                 size_t sizeout)
{
    if (ctx->status != POSEIDON_INITIALIZED)
        return ZKN_NOT_INITIALIZED;

    ZKN_CHECK(zkn_bn_set_u32(ctx->state[0], initState));

    /* state[0] must be montgomerized too */
    ZKN_CHECK(zkn_mont_to_montgomery(ctx->state[0], ctx->state[0], ctx->mont));

    size_t nRoundsF = ctx->rounds_f;
    size_t nRoundsP = ctx->rounds_p;

    for (size_t r = 0; r < nRoundsF + nRoundsP; r++) {
        ZKN_CHECK(poseidon_add_round_c(ctx));

        if (r < nRoundsF / 2 || r >= nRoundsF / 2 + nRoundsP) {
            /* Full rounds: S-box on all cells */
            ZKN_CHECK(poseidon_sigma(ctx));
        } else {
            /* Partial rounds: S-box only on state[0] */
            uint8_t exp5[1] = {5};
            ZKN_CHECK(zkn_mont_pow(ctx->state[0], ctx->state[0],
                                   exp5, 1, ctx->mont));
        }

        ZKN_CHECK(poseidon_mix(ctx));
    }

    for (size_t i = 0; i < sizeout; i++) {
        ZKN_CHECK(zkn_bn_copy(out[i], ctx->state[i]));
    }

    return ZKN_OK;
}

int zkn_poseidon_hash(const uint8_t *inputs,
                      size_t nb_inputs,
                      uint8_t out[32])
{
    if (nb_inputs > POSEIDON_MAX_INPUTS || nb_inputs == 0)
        return ZKN_INVALID_PARAM;

    /* Init Montgomery context */
    zkn_bn_mont_ctx_t montctx;
    zkn_bn_t modulus;
    ZKN_CHECK(zkn_bn_alloc_init(&modulus, 32, BJJ_PRIME_BE, 32));
    ZKN_CHECK(zkn_mont_alloc(&montctx, 32));
    ZKN_CHECK(zkn_mont_init(&montctx, modulus));

    /* Init Poseidon */
    poseidon_soft_ctx_t ctx;
    ZKN_CHECK(zkn_poseidon_init(&ctx, 5, nb_inputs, &montctx));

    /* Load inputs into state[1..nb_inputs] in Montgomery form */
    for (size_t i = 0; i < nb_inputs; i++) {
        ZKN_CHECK(zkn_bn_init(ctx.state[i + 1], inputs + 32 * i, 32));
        ZKN_CHECK(zkn_mont_to_montgomery(ctx.state[i + 1],
                                         ctx.state[i + 1], &montctx));
    }

    /* Hash */
    zkn_bn_t result;
    ZKN_CHECK(zkn_poseidon(&ctx, 0, &result, 1));

    /* De-montgomerize and export */
    ZKN_CHECK(zkn_mont_from_montgomery(result, result, &montctx));
    ZKN_CHECK(zkn_bn_export(result, out, 32));

    return ZKN_OK;
}
